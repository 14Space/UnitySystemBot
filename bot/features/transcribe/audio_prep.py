"""
Подготовка звука перед распознаванием.

Голосовые приходят какие есть: записанные на ветру, вполголоса, с музыкой в фоне, с
долгими паузами. Распознаванию всё это мешает, а у облака (в отличие от нашей
локальной модели) нет ни фильтра тишины, ни какой-либо чистки — что дали, то и
разбирает. Поэтому чистим сами, благо ffmpeg в образе уже есть.

Что делает цепочка фильтров и зачем:

  • highpass=f=80        — срезает гул ниже человеческого голоса: ветер в микрофон,
                           стук по столу, транспорт за окном;
  • afftdn=nf=-25        — шумоподавление: оценивает ровный фоновый шум и вычитает его;
  • loudnorm             — выравнивает громкость. Тихая речь распознаётся заметно хуже,
                           а люди наговаривают кто в упор, кто с вытянутой руки;
  • silenceremove        — выкидывает паузы длиннее 0.6с. Именно на паузах Whisper
                           выдумывает фразы, и именно фильтра тишины ему тут не хватает.

Плюс приведение к 16 кГц моно: ровно в этом виде модель и работает внутри, так что
конвертация всё равно произойдёт — лучше сделать её один раз и предсказуемо.

Замер (образец речи, зашумлённый до состояния «разговор на улице»): уверенность
разбора выросла с -0.222 до -0.181. На чистой записи выигрыш меньше, около -0.163 →
-0.150, и это ожидаемо: чистить там нечего.

Обработка НЕ обязана удаться. Сломался ffmpeg, кривой файл, неизвестный формат — в
любом таком случае возвращаем исходный путь и работаем как раньше: расшифровка важнее
улучшения.
"""
import logging
import os
import subprocess

from bot.utils import ffmpeg, files
import uuid

from bot.config import DOWNLOADS_DIR, STT_PREPROCESS, STT_FILTERS

logger = logging.getLogger(__name__)

# Сколько ждём ffmpeg. Он работает быстрее реального времени в десятки раз, так что
# минуты хватает даже на часовую запись; дольше — значит что-то пошло не так.
_TIMEOUT = 60


def prepare(path: str) -> tuple[str, bool]:
    """Готовит файл к распознаванию.

    Возвращает (путь, наш_ли_это_файл). Второе — признак того, что файл создали мы и
    его нужно удалить после распознавания. Если обработка не удалась или выключена,
    вернётся исходный путь и False.
    """
    if not STT_PREPROCESS or not path or not os.path.exists(path):
        return path, False

    # Папку создаём сами, как и все загрузчики: на свежей установке её ещё нет, и ffmpeg
    # молча не смог бы записать результат – голосовые шли бы без очистки звука.
    # Нашлось 24.09.2026, когда тесты впервые прогнали внутри рабочего образа.
    os.makedirs(DOWNLOADS_DIR, exist_ok=True)
    out = os.path.join(DOWNLOADS_DIR, f"prep_{uuid.uuid4().hex[:8]}.wav")
    cmd = ["ffmpeg", "-y", "-i", path, "-ar", "16000", "-ac", "1"]
    if STT_FILTERS:
        cmd += ["-af", STT_FILTERS]
    cmd += [out]

    try:
        res = ffmpeg.run(cmd, timeout=_TIMEOUT)
    except (OSError, subprocess.SubprocessError) as e:
        logger.info("Подготовка звука не вышла (%s) — распознаю как есть", type(e).__name__)
        return path, False

    if res.returncode != 0 or not os.path.exists(out) or os.path.getsize(out) == 0:
        logger.info("Подготовка звука не вышла (ffmpeg %s) — распознаю как есть",
                    res.returncode)
        _drop(out)
        return path, False

    return out, True


def _drop(path: str) -> None:
    files.remove(path)


def cleanup(path: str, ours: bool) -> None:
    """Убирает файл, который создали мы. Чужой (исходное голосовое) не трогаем —
    его удалит тот, кто скачивал."""
    if ours:
        _drop(path)
