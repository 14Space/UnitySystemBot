"""
Есть ли в записи речь – ДО того, как отдавать её распознаванию.

Зачем. Whisper, получив тишину, не молчит, а выдумывает: заученные из обучающих данных
подписи к видео («Субтитры сделал…», «Subtitles by the Amara.org community»,
«Продолжение следует…»). Раньше мы вырезали такие фразы по списку, но список всегда
отстаёт: 23.09.2026 на молчаливом кружке бот ответил «Субтитры добавил» – той
формулировки в списке не было. Полагаться на сигнал самого облака тоже нельзя:
повторный разбор 24.09.2026 показал, что Groq на шести секундах тишины уверенно
пишет «Subtitles by the Amara.org community» и при этом сообщает вероятность тишины
0.02, то есть «речь почти наверняка есть».

Поэтому тишину распознаванию не отдаём вовсе. Детектор речи Silero VAD – тот самый
фильтр тишины, который был у нашей локальной модели (он приходит вместе с пакетом
faster-whisper, отдельной загрузки не требует). Замер на сервере: тишина, шум
комнаты, громкий шум и чистый тон – 0 секунд речи; настоящий образец голоса – 6.45 из
6.8 секунды; работает за 0.06 секунды на запись.

Детектор – страховка, а не новая точка отказа: не смог он разобрать файл или его нет
в окружении – возвращаем None, и расшифровка идёт как раньше.
"""
import logging

logger = logging.getLogger(__name__)

_RATE = 16000


def speech_seconds(path: str) -> float | None:
    """Сколько секунд речи в записи. None – определить не вышло (тогда не мешаем)."""
    try:
        from faster_whisper.audio import decode_audio
        from faster_whisper.vad import VadOptions, get_speech_timestamps

        audio = decode_audio(path, sampling_rate=_RATE)
        spans = get_speech_timestamps(audio, VadOptions())
        return sum(s["end"] - s["start"] for s in spans) / _RATE
    except Exception:
        logger.info("Детектор речи не справился с файлом — расшифровываю как есть",
                    exc_info=True)
        return None
