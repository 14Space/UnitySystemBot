"""
Один предел времени на все запуски ffmpeg и ffprobe.

Зачем отдельным модулем. Внешний аудит нашёл десяток мест, где эти программы
запускались БЕЗ предела времени: ffmpeg и ffprobe вызываются на каждое видео, на
каждое голосовое и на каждую обложку. Зависший процесс (битый файл, обрыв потока,
невнятный кодек) держал бы поток из пула и слот очереди до самого сторожа зависаний,
то есть сорок минут — и всё это молча.

Величина с запасом: перекодирование идёт в разы быстрее реального времени, так что
получасового предела хватает даже фильму с HDRezka. Смысл не в том, чтобы угадать
точно, а в том, чтобы «навсегда» стало «не дольше получаса».
"""
