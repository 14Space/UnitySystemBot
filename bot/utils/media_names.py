"""
Названия скачанных файлов: от загрузчика к отправке.

Зачем отдельный реестр. Файл скачивается под техническим именем (уникальным, иначе
параллельные загрузки затирают друг друга), а человеку должно прийти «Название [1080p]
@UnitySystemBot.mp4». Название знает только загрузчик — оно приходит от площадки вместе
с файлом. Место отправки видит один лишь путь.

Тащить название через все слои пришлось бы, поменяв тип возврата у десятка функций и
всех, кто их зовёт. Вместо этого загрузчик оставляет здесь запись «путь → название», а
отправка её забирает.

Почему это безопасно при одновременных скачиваниях: ключ — ПОЛНЫЙ ПУТЬ, а он уникален
для каждого скачивания (см. _unique_outtmpl). Перепутать записи невозможно.
"""
import os
import threading

# Записи «путь → (название, технический номер)». Складывать сюда можно из любого потока:
# скачивание живёт в asyncio.to_thread, то есть в пуле потоков, а не в основном цикле.
#
# Номер храним рядом с названием, а не вычленяем потом из имени файла: во временном
# имени он идёт первым куском до подчёркивания, но у самих площадок номера бывают с
# подчёркиванием внутри, и разбор ломался бы на них молча.
_titles: dict[str, tuple[str | None, str | None]] = {}
_lock = threading.Lock()

# Потолок на случай, если какие-то записи не заберут (файл не отправился, упала
# отправка). Без него словарь рос бы всю жизнь процесса.
_MAX = 500


def remember(path: str, title: str | None, ident: str | None = None) -> None:
    """Запоминает название и технический номер скачанного файла."""
    if not path or not (title or ident):
        return
    with _lock:
        if len(_titles) >= _MAX:
            # Вычищаем записи, чьих файлов уже нет — это как раз забытые хвосты.
            for p in [p for p in _titles if not os.path.exists(p)]:
                _titles.pop(p, None)
            if len(_titles) >= _MAX:            # всё ещё тесно — жертвуем самой старой
                _titles.pop(next(iter(_titles)), None)
        _titles[path] = (title, ident)


def peek(path: str) -> tuple[str | None, str | None]:
    """Название и номер файла. Запись не убираем: файл может отправляться не один раз."""
    with _lock:
        return _titles.get(path, (None, None))


def title_of(path: str) -> str | None:
    return peek(path)[0]


def ident_of(path: str) -> str | None:
    return peek(path)[1]
